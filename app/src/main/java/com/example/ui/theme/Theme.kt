private val DarkColorScheme = darkColorScheme(
    primary = NavyLight,
    onPrimary = Color.Black,
    primaryContainer = NavyDark,
    onPrimaryContainer = Color(0xFFDBEAFE),
    secondary = Color(0xFF38BDF8),
    onSecondary = Color.Black,
